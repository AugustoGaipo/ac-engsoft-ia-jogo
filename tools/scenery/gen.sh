#!/usr/bin/env bash
# Generates a scenery scene (.tscn) from a box table: solid StaticBody3D boxes (convex shapes, so a body
# deep inside one is detected), one mesh + one box shape each, on the "world" layer; optional Label3D signs.
# Usage: tools/scenery/gen.sh <root-name> <boxes-file> <out.tscn> [signs-file] [sun-x sun-z]
# With PREVIEW=res://path/to/level.json, adds the editor-only LevelPreview node (pieces drawn from the JSON).
set -euo pipefail
root=$1 boxes=$2 out=$3 signs=${4:-} sunx=${5:-24} sunz=${6:-5}
{
cat <<HDR
[gd_scene format=3]
HDR
if [ -n "${PREVIEW:-}" ]; then printf '
[ext_resource type="Script" path="res://scripts/LevelPreview.cs" id="preview"]
'; fi
cat <<HDR

[ext_resource type="Shader" path="res://shaders/lab_panel.gdshader" id="panel"]

[sub_resource type="ShaderMaterial" id="floor"]
shader = ExtResource("panel")
shader_parameter/base_color = Color(0.40, 0.42, 0.45, 1)
shader_parameter/seam_color = Color(0.20, 0.21, 0.23, 1)
shader_parameter/panel_size = 1.0
shader_parameter/seam_width = 0.025
shader_parameter/variation = 0.06
shader_parameter/roughness_value = 0.7

[sub_resource type="ShaderMaterial" id="wall"]
shader = ExtResource("panel")
shader_parameter/base_color = Color(0.88, 0.89, 0.90, 1)
shader_parameter/seam_color = Color(0.42, 0.45, 0.50, 1)
shader_parameter/panel_size = 1.5
shader_parameter/seam_width = 0.03
shader_parameter/variation = 0.04
shader_parameter/roughness_value = 0.5

[sub_resource type="ShaderMaterial" id="ledge"]
shader = ExtResource("panel")
shader_parameter/base_color = Color(0.95, 0.74, 0.16, 1)
shader_parameter/seam_color = Color(0.22, 0.18, 0.08, 1)
shader_parameter/panel_size = 1.0
shader_parameter/seam_width = 0.04
shader_parameter/variation = 0.05
shader_parameter/roughness_value = 0.6

[sub_resource type="ShaderMaterial" id="pit"]
shader = ExtResource("panel")
shader_parameter/base_color = Color(0.07, 0.06, 0.07, 1)
shader_parameter/seam_color = Color(0.75, 0.08, 0.06, 1)
shader_parameter/panel_size = 1.0
shader_parameter/seam_width = 0.05
shader_parameter/variation = 0.0
shader_parameter/roughness_value = 0.9
shader_parameter/emission_color = Color(0.18, 0.01, 0.01, 1)

[sub_resource type="Environment" id="env"]
background_mode = 1
background_color = Color(0.09, 0.11, 0.14, 1)
ambient_light_source = 2
ambient_light_color = Color(0.85, 0.9, 1, 1)
ambient_light_energy = 0.6
tonemap_mode = 2
glow_enabled = true
ssao_enabled = true
HDR
grep -v '^#' "$boxes" | awk '{ printf "\n[sub_resource type=\"BoxMesh\" id=\"mesh_%s\"]\nmaterial = SubResource(\"%s\")\nsize = Vector3(%g, %g, %g)\n\n[sub_resource type=\"BoxShape3D\" id=\"shape_%s\"]\nsize = Vector3(%g, %g, %g)\n", $1, $2, $6-$3, $7-$4, $8-$5, $1, $6-$3, $7-$4, $8-$5 }'
cat <<HDR

; Generated by tools/scenery/gen.sh from $(basename "$boxes") — edit the table, not this file.
[node name="$root" type="Node3D"]

[node name="Environment" type="WorldEnvironment" parent="."]
environment = SubResource("env")

[node name="Sun" type="DirectionalLight3D" parent="."]
transform = Transform3D(0.866025, -0.25, 0.433013, 0, 0.866025, 0.5, -0.5, -0.433013, 0.75, $sunx, 12, $sunz)
shadow_enabled = true
HDR
grep -v '^#' "$boxes" | awk '{ printf "\n[node name=\"%s\" type=\"StaticBody3D\" parent=\".\"]\ntransform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %g, %g, %g)\n\n[node name=\"Mesh\" type=\"MeshInstance3D\" parent=\"%s\"]\nmesh = SubResource(\"mesh_%s\")\n\n[node name=\"Shape\" type=\"CollisionShape3D\" parent=\"%s\"]\nshape = SubResource(\"shape_%s\")\n", $1, ($3+$6)/2, ($4+$7)/2, ($5+$8)/2, $1, $1, $1, $1 }'
if [ -n "$signs" ]; then
grep -v '^#' "$signs" | awk -F'|' '{ split($2, p, " "); printf "\n[node name=\"%s\" type=\"Label3D\" parent=\".\"]\ntransform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %s, %s, %s)\nbillboard = 1\npixel_size = 0.006\nfont_size = 48\noutline_size = 12\ntext = \"%s\"\n", $1, p[1], p[2], p[3], $3 }'
fi
if [ -n "${PREVIEW:-}" ]; then printf '
[node name="Preview" type="Node3D" parent="."]
script = ExtResource("preview")
LevelFile = "%s"
' "$PREVIEW"; fi
} > "$out"
echo "wrote $out"
